import pandas as pd
file_path="../data/raw file/Telco_Customer_Churn_Dataset.csv"
df=pd.read_csv(file_path)
print("Shape",df.shape)
print("\ncolumns:",df.columns.tolist())
print("\nNumeric Summary:",df.describe())
print("\nCategorial Summary:",df.describe(include='str'))
print("="*80)
print("\nMissing values:",df.isnull().sum())
print("\nDuplicated values:",df.duplicated().sum())
print("\nData types:",df.dtypes)
print("="*80)
#converting Total charges (str) into numeric
df_raw=df.copy()
df.columns=df.columns.str.strip().str.lower().str.replace(' ', '_')
print("\nraw:",df_raw)
print("\nraw cols:",df_raw.columns)
print("\n copy cols",df.columns)
print("\ndf copy:",df)
print("="*80)
df["totalcharges"]=pd.to_numeric(df["totalcharges"].str.strip().replace("",pd.NA),errors='coerce')
print("updates data type  :",df["totalcharges"].dtype)
print("Missing values:",df["totalcharges"].isnull().sum())
print(df.loc[df["totalcharges"].isna(),["tenure","totalcharges"]])
df["totalcharges"]=df["totalcharges"].fillna(0)
print("Missing values:",df["totalcharges"].isnull().sum())
print("="*80)
print("------------------------------ Final check ----------------------------------------------------")
print("Shape",df.shape)
print("\nMissing values:",df.isnull().sum())
print("\nDuplicated values:",df.duplicated().sum())
print("\nData types:",df.dtypes)

df.to_csv("../data/processed/cleaned_telco.csv",index=False)
print("File created")
print("="*80)